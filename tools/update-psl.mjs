// Regenerate src/core/psl-data.js from the Public Suffix List (ICANN + private sections).
// Rules are stored punycoded, the form hostnames take in URLs. Usage: node tools/update-psl.mjs
import { writeFile } from "node:fs/promises";

const url = "https://publicsuffix.org/list/public_suffix_list.dat";
const res = await fetch(url);
if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);

const toAscii = (name) => new URL(`http://${name}`).hostname;
const rules = [];
for (const line of (await res.text()).split("\n")) {
  const rule = line.trim().split(/\s/)[0];
  if (!rule || rule.startsWith("//")) continue;
  if (rule.startsWith("!")) rules.push(`!${toAscii(rule.slice(1))}`);
  else if (rule.startsWith("*.")) rules.push(`*.${toAscii(rule.slice(2))}`);
  else rules.push(toAscii(rule));
}

await writeFile(
  new URL("../src/core/psl-data.js", import.meta.url),
  `// Generated by tools/update-psl.mjs from ${url} — do not edit.\nexport default ${JSON.stringify(rules.join("\n"))}.split("\\n");\n`,
);
console.log(`psl-data.js: ${rules.length} rules`);
